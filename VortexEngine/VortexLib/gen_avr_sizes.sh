#!/bin/bash
#
# Generates AvrSizes.h which maps the host sizeof() of every class the engine
# allocates with 'new' to the sizeof() of that same class on the attiny3217.
#
# The heap tracker (HEAP_TRACKING in Memory.cpp) uses this table to charge each
# allocation the number of bytes it would really take on the device so that the
# simulated heap behaves like the real one. Re-run this whenever a class that
# is allocated with 'new' changes size:
#
#   ./gen_avr_sizes.sh > AvrSizes.h
#

cd "$(dirname "$0")/../src" || exit 1

PROBE=$(mktemp --suffix=.cpp)
trap 'rm -f $PROBE' EXIT

# every class that is allocated with 'new'
PATTERNS=$(grep -o "new [A-Za-z]*Pattern" Patterns/PatternBuilder.cpp | cut -d' ' -f2 | sort -u)
MENUS=$(grep -o "^  ENTRY([A-Za-z]*" Menus/Menus.cpp | cut -d'(' -f2 | sort -u)
CLASSES="Button Mode Modes::ModeLink $PATTERNS $MENUS"

{
  echo '#include "VortexConfig.h"'
  echo '#include "Buttons/Button.h"'
  echo '#include "Modes/Mode.h"'
  echo '#include "Modes/Modes.h"'
  grep "#include \"Multi\|#include \"Single" Patterns/PatternBuilder.cpp | sed 's,"\(Multi\|Single\),"Patterns/\1,'
  grep "#include \"MenuList" Menus/Menus.cpp | sed 's,"MenuList,"Menus/MenuList,'
  echo 'template <int N> struct Size;'
  i=0
  for c in $CLASSES; do
    echo "Size<sizeof($c)> v$i;"
    i=$((i + 1))
  done
} > $PROBE

# compile the probe and pull the sizes out of the 'incomplete type' errors
sizes() {
  "$@" -fsyntax-only -fno-access-control -I. $PROBE 2>&1 | \
    grep -o "Size<[0-9]*> v[0-9]*" | sed 's/Size<\([0-9]*\)> v\([0-9]*\)/\2 \1/' | sort -n | cut -d' ' -f2
}
AVR=($(sizes avr-g++ -std=gnu++17 -Os -fshort-enums -fpack-struct -funsigned-char \
  -mmcu=attiny3217 -D__AVR_ATtiny3217__ -DF_CPU=10000000))
# the host sizes for both the regular and the slim (VORTEX_LIB_SLIM) build
HOST=($(sizes g++ -std=gnu++17 -DVORTEX_LIB -I../VortexLib))
HOST_SLIM=($(sizes g++ -std=gnu++17 -DVORTEX_LIB -DVORTEX_LIB_SLIM -I../VortexLib))

NAMES=($CLASSES)
if [ ${#AVR[@]} -ne ${#NAMES[@]} ] || [ ${#HOST[@]} -ne ${#NAMES[@]} ] || [ ${#HOST_SLIM[@]} -ne ${#NAMES[@]} ]; then
  echo "Failed to probe sizes (${#NAMES[@]} classes, ${#AVR[@]} avr, ${#HOST[@]} host, ${#HOST_SLIM[@]} slim)" >&2
  exit 1
fi

table() {
  local -n host=$1
  for i in "${!NAMES[@]}"; do
    printf "  { %4u, %4u, \"%s\" },\n" "${host[$i]}" "${AVR[$i]}" "${NAMES[$i]}"
  done
}

echo "// generated by gen_avr_sizes.sh, do not edit"
echo "// { host sizeof, attiny3217 sizeof } of every class allocated with new"
echo "static const struct { uint16_t host; uint16_t avr; const char *name; } avrSizes[] = {"
echo "#if VORTEX_SLIM == 1"
table HOST_SLIM
echo "#else"
table HOST
echo "#endif"
echo "};"
